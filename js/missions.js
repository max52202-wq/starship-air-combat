  function getById(id) {
    return LIST.find((m) => m.id === id) || LIST[0];
  }

  function getNext(id) {
    const idx = LIST.findIndex((m) => m.id === id);
    if (idx < 0 || idx + 1 >= LIST.length) return null;
    return LIST[idx + 1];
  }

