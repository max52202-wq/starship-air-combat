  const STORAGE_KEY = "starfleet_solar_cleared_v1";
  const SHIP_STORAGE_KEY = "starfleet_selected_ship_v1";
  const DIFF_STORAGE_KEY = "starfleet_difficulty_v1";

  function loadDifficultyId() {
    try {
      return localStorage.getItem(DIFF_STORAGE_KEY) || "normal";
    } catch (_) {
      return "normal";
    }
  }

  function saveDifficultyId(id) {
    try {
      localStorage.setItem(DIFF_STORAGE_KEY, id);
    } catch (_) {}
  }

  function getDifficultyById(id) {
    return DIFFICULTIES.find((d) => d.id === id) || DIFFICULTIES[1];
  }

  function loadCleared() {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      const arr = raw ? JSON.parse(raw) : [];
      return new Set(Array.isArray(arr) ? arr : []);
    } catch (_) {
      return new Set();
    }
  }

  function saveCleared(set) {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(Array.from(set)));
    } catch (_) {}
  }

  function loadSelectedShipId() {
    try {
      return localStorage.getItem(SHIP_STORAGE_KEY) || "tiny_fighter";
    } catch (_) {
      return "tiny_fighter";
    }
  }

  function saveSelectedShipId(id) {
    try {
      localStorage.setItem(SHIP_STORAGE_KEY, id);
    } catch (_) {}
  }

